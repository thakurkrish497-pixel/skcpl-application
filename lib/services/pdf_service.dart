import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:intl/intl.dart';
import '../models/stock_transaction_model.dart';
import '../models/cash_transaction_model.dart';

class PdfService {
  static Future<void> generateAndPrintStockReceipt(
      StockTransactionModel tx, String siteName, [String? productName, String? unitName]) async {
    final effectiveProduct = (productName != null && productName != 'Unknown') ? productName : tx.displayProductName;
    final effectiveUnit = (unitName != null && unitName.isNotEmpty) ? unitName : tx.displayMetricUnitName;
    final pdf = pw.Document();

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Header(
                level: 0,
                child: pw.Text('SKCPL - Transaction Receipt',
                    style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold)),
              ),
              pw.SizedBox(height: 20),
              pw.Text('Site: $siteName', style: const pw.TextStyle(fontSize: 16)),
              pw.Text('Type: ${tx.type.name.toUpperCase()}', style: const pw.TextStyle(fontSize: 16)),
              pw.Text('Status: ${tx.status.name.toUpperCase()}', style: const pw.TextStyle(fontSize: 16)),
              pw.Text('Date: ${DateFormat('dd MMM yyyy').format(tx.date)}', style: const pw.TextStyle(fontSize: 16)),
              pw.SizedBox(height: 20),
              pw.TableHelper.fromTextArray(
                context: context,
                data: <List<String>>[
                  ['Detail', 'Value'],
                  ['Product', effectiveProduct],
                  ['Quantity', '${tx.quantity} $effectiveUnit'],
                  if (tx.rate != null && tx.type.name == 'inbound') ['Rate', '₹${tx.rate}'],
                  if (tx.finalAmount != null && tx.type.name == 'inbound') ['Total Amount', '₹${tx.finalAmount}'],
                  if (tx.billNo != null) ['Bill / Ref No', tx.billNo!],
                  if (tx.cleanRemarks != null) ['Remarks', tx.cleanRemarks!],
                  if (tx.displayVendorName != 'None') ['Vendor / Party', tx.displayVendorName],
                ],
              ),
              pw.SizedBox(height: 40),
              pw.Text('Generated by SKCPL Management System',
                  style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey)),
            ],
          );
        },
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: 'SKCPL_Receipt_${tx.id ?? 'receipt'}.pdf',
    );
  }

  /// Generates a comprehensive, branded Daily Site Summary Sheet
  static Future<void> generateAndPrintDailySummary({
    required String siteName,
    required DateTime date,
    required List<StockTransactionModel> stockTransactions,
    required List<CashTransactionModel> cashTransactions,
    String? siteLoginId,
  }) async {
    final pdf = pw.Document();
    final dateKey = DateFormat('yyyy-MM-dd').format(date);
    final currencyFmt = NumberFormat.currency(locale: 'en_IN', symbol: 'Rs. ', decimalDigits: 0);

    // Filter day data
    final dayCash = cashTransactions
        .where((c) => DateFormat('yyyy-MM-dd').format(c.date) == dateKey)
        .toList();
    final dayStock = stockTransactions
        .where((s) => DateFormat('yyyy-MM-dd').format(s.date) == dateKey)
        .toList();

    double totalInboundCash = 0;
    double totalOutboundCash = 0;
    for (final c in dayCash) {
      totalInboundCash += c.amountReceived;
      totalOutboundCash += c.expenseAmount;
    }
    final netCash = totalInboundCash - totalOutboundCash;

    final inboundStock = dayStock.where((s) => s.type == TransactionType.inbound).toList();
    final outboundStock = dayStock.where((s) => s.type == TransactionType.outbound).toList();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) {
          return [
            // Company Header Banner
            pw.Container(
              padding: const pw.EdgeInsets.symmetric(vertical: 12, horizontal: 16),
              decoration: pw.BoxDecoration(
                color: PdfColors.blueGrey900,
                borderRadius: pw.BorderRadius.circular(8),
              ),
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'SKCPL CONSTRUCTION MANAGEMENT',
                        style: pw.TextStyle(
                          color: PdfColors.white,
                          fontSize: 16,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                      pw.Text(
                        'DAILY SITE PROGRESS & CASHFLOW REPORT',
                        style: const pw.TextStyle(
                          color: PdfColors.blueGrey100,
                          fontSize: 10,
                        ),
                      ),
                    ],
                  ),
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.end,
                    children: [
                      pw.Text(
                        'Site: $siteName',
                        style: pw.TextStyle(
                          color: PdfColors.amber,
                          fontSize: 12,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                      pw.Text(
                        'Date: ${DateFormat('dd MMM yyyy').format(date)}',
                        style: const pw.TextStyle(color: PdfColors.white, fontSize: 10),
                      ),
                    ],
                  ),
                ],
              ),
            ),

            pw.SizedBox(height: 16),

            // KPI Overview Cards
            pw.Row(
              children: [
                _buildKpiCard('Cash Received', currencyFmt.format(totalInboundCash), PdfColors.green700),
                pw.SizedBox(width: 8),
                _buildKpiCard('Site Expenses', currencyFmt.format(totalOutboundCash), PdfColors.red700),
                pw.SizedBox(width: 8),
                _buildKpiCard('Net Day Balance', currencyFmt.format(netCash), PdfColors.blue700),
                pw.SizedBox(width: 8),
                _buildKpiCard('Materials Logged', '${inboundStock.length} In / ${outboundStock.length} Out', PdfColors.orange700),
              ],
            ),

            pw.SizedBox(height: 20),

            // Section 1: Cash Transactions Table
            pw.Text(
              '1. Cash Book & Expense Log',
              style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800),
            ),
            pw.SizedBox(height: 6),
            if (dayCash.isEmpty)
              pw.Container(
                padding: const pw.EdgeInsets.all(10),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: PdfColors.grey300),
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Center(
                  child: pw.Text('No cash transactions logged for this date.',
                      style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
                ),
              )
            else
              pw.TableHelper.fromTextArray(
                context: context,
                headerStyle: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
                headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey700),
                cellStyle: const pw.TextStyle(fontSize: 8),
                cellPadding: const pw.EdgeInsets.symmetric(vertical: 5, horizontal: 8),
                headers: ['Expense Type', 'Party / Vendor', 'Bill No.', 'Remarks', 'Received', 'Expense', 'Status'],
                data: dayCash.map((c) {
                  return [
                    c.displayExpenseTypeName,
                    c.partyName ?? '-',
                    c.billNo ?? '-',
                    c.cleanRemarks ?? '-',
                    c.amountReceived > 0 ? currencyFmt.format(c.amountReceived) : '-',
                    c.expenseAmount > 0 ? currencyFmt.format(c.expenseAmount) : '-',
                    c.status.name.toUpperCase(),
                  ];
                }).toList(),
              ),

            pw.SizedBox(height: 20),

            // Section 2: Materials Inbound (Deliveries)
            pw.Text(
              '2. Material Deliveries Received (Inbound)',
              style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800),
            ),
            pw.SizedBox(height: 6),
            if (inboundStock.isEmpty)
              pw.Container(
                padding: const pw.EdgeInsets.all(10),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: PdfColors.grey300),
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Center(
                  child: pw.Text('No material deliveries recorded for this date.',
                      style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
                ),
              )
            else
              pw.TableHelper.fromTextArray(
                context: context,
                headerStyle: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
                headerDecoration: const pw.BoxDecoration(color: PdfColors.teal700),
                cellStyle: const pw.TextStyle(fontSize: 8),
                cellPadding: const pw.EdgeInsets.symmetric(vertical: 5, horizontal: 8),
                headers: ['Material', 'Quantity', 'Vendor / Party', 'Challan / Bill No.', 'Remarks', 'Status'],
                data: inboundStock.map((s) {
                  return [
                    s.displayProductName,
                    '${s.quantity} ${s.displayMetricUnitName}',
                    s.displayVendorName,
                    s.billNo ?? '-',
                    s.cleanRemarks ?? '-',
                    s.status.name.toUpperCase(),
                  ];
                }).toList(),
              ),

            pw.SizedBox(height: 20),

            // Section 3: Material Consumption (Outbound)
            pw.Text(
              '3. Material Consumption on Site (Outbound)',
              style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800),
            ),
            pw.SizedBox(height: 6),
            if (outboundStock.isEmpty)
              pw.Container(
                padding: const pw.EdgeInsets.all(10),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: PdfColors.grey300),
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Center(
                  child: pw.Text('No material consumption recorded for this date.',
                      style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
                ),
              )
            else
              pw.TableHelper.fromTextArray(
                context: context,
                headerStyle: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
                headerDecoration: const pw.BoxDecoration(color: PdfColors.brown700),
                cellStyle: const pw.TextStyle(fontSize: 8),
                cellPadding: const pw.EdgeInsets.symmetric(vertical: 5, horizontal: 8),
                headers: ['Material', 'Quantity Consumed', 'Slip / Ref No.', 'Purpose / Activity Location', 'Status'],
                data: outboundStock.map((s) {
                  return [
                    s.displayProductName,
                    '${s.quantity} ${s.displayMetricUnitName}',
                    s.billNo ?? '-',
                    s.cleanRemarks ?? 'General Site Construction',
                    s.status.name.toUpperCase(),
                  ];
                }).toList(),
              ),

            pw.SizedBox(height: 35),

            // Signatures block
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                _buildSignatureBox('Site Supervisor / In-Charge'),
                _buildSignatureBox('Accounts Verification'),
                _buildSignatureBox('Project Manager / Director'),
              ],
            ),

            pw.SizedBox(height: 15),

            pw.Center(
              child: pw.Text(
                'Report generated on ${DateFormat('dd MMM yyyy, hh:mm a').format(DateTime.now())} • SKCPL App',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
              ),
            ),
          ];
        },
      ),
    );

    final cleanSite = siteName.replaceAll(RegExp(r'\s+'), '_');
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: 'SKCPL_DailySummary_${cleanSite}_$dateKey.pdf',
    );
  }

  static pw.Widget _buildKpiCard(String title, String value, PdfColor color) {
    return pw.Expanded(
      child: pw.Container(
        padding: const pw.EdgeInsets.all(8),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: color, width: 1),
          borderRadius: pw.BorderRadius.circular(6),
          color: PdfColors.grey100,
        ),
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(title, style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700)),
            pw.SizedBox(height: 4),
            pw.Text(value, style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: color)),
          ],
        ),
      ),
    );
  }

  static pw.Widget _buildSignatureBox(String label) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.center,
      children: [
        pw.Container(width: 140, height: 1, color: PdfColors.grey500),
        pw.SizedBox(height: 4),
        pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700)),
      ],
    );
  }
}
