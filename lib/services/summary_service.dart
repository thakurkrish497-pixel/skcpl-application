import 'package:flutter/services.dart';
import 'package:url_launcher/url_launcher.dart';
import 'package:intl/intl.dart';
import '../models/stock_transaction_model.dart';
import '../models/cash_transaction_model.dart';
import 'pdf_service.dart';

/// Aggregates daily site statistics, formats WhatsApp text summaries,
/// and coordinates branded PDF report generation.
class SummaryService {
  /// Aggregates and formats a complete daily site report into WhatsApp Markdown.
  static String buildWhatsAppSummary({
    required String siteName,
    required DateTime date,
    required List<StockTransactionModel> stockTransactions,
    required List<CashTransactionModel> cashTransactions,
    String? siteLoginId,
  }) {
    final currencyFmt = NumberFormat.currency(locale: 'en_IN', symbol: '₹', decimalDigits: 0);
    final dateStr = DateFormat('dd MMM yyyy (EEEE)').format(date);

    // Filter transactions strictly for the given date
    final dateKey = DateFormat('yyyy-MM-dd').format(date);

    final dayCash = cashTransactions.where((c) {
      return DateFormat('yyyy-MM-dd').format(c.date) == dateKey;
    }).toList();

    final dayStock = stockTransactions.where((s) {
      return DateFormat('yyyy-MM-dd').format(s.date) == dateKey;
    }).toList();

    // ── Cash stats ──
    double totalInboundCash = 0;
    double totalOutboundCash = 0;
    final Map<String, double> expenseByCategory = {};

    for (final c in dayCash) {
      totalInboundCash += c.amountReceived;
      totalOutboundCash += c.expenseAmount;

      final cat = c.displayExpenseTypeName;
      expenseByCategory[cat] = (expenseByCategory[cat] ?? 0) + c.expenseAmount;
    }

    final netCashToday = totalInboundCash - totalOutboundCash;

    // ── Stock stats ──
    final inboundStock = dayStock.where((s) => s.type == TransactionType.inbound).toList();
    final outboundStock = dayStock.where((s) => s.type == TransactionType.outbound).toList();

    final buffer = StringBuffer();
    buffer.writeln('🏗️ *SKCPL — DAILY SITE SUMMARY*');
    buffer.writeln('━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('📍 *Site:* $siteName');
    if (siteLoginId != null && siteLoginId.isNotEmpty) {
      buffer.writeln('👷 *Site ID:* $siteLoginId');
    }
    buffer.writeln('📅 *Date:* $dateStr');
    buffer.writeln('');

    // Cash Section
    buffer.writeln('💰 *CASH & PETTY EXPENSES*');
    buffer.writeln('• Cash Received Today: ${currencyFmt.format(totalInboundCash)}');
    buffer.writeln('• Site Expenses Today: ${currencyFmt.format(totalOutboundCash)}');
    buffer.writeln('• *Net Day Balance:* ${currencyFmt.format(netCashToday)}');

    if (expenseByCategory.isNotEmpty) {
      buffer.writeln('\n_Expense Breakdown:_');
      expenseByCategory.forEach((cat, amt) {
        buffer.writeln('  ▫️ $cat: ${currencyFmt.format(amt)}');
      });
    } else {
      buffer.writeln('  ▫️ _No cash expenses recorded today_');
    }

    buffer.writeln('\n━━━━━━━━━━━━━━━━━━━━');

    // Stock Inbound
    buffer.writeln('📦 *MATERIALS RECEIVED (INBOUND)*');
    if (inboundStock.isNotEmpty) {
      for (final s in inboundStock) {
        final prod = s.displayProductName;
        final qty = '${s.quantity} ${s.displayMetricUnitName}';
        final vendor = s.displayVendorName;
        buffer.writeln('  ✅ $prod: +$qty ($vendor)');
      }
    } else {
      buffer.writeln('  _No inbound deliveries received today_');
    }

    buffer.writeln('');

    // Stock Outbound
    buffer.writeln('🔨 *MATERIALS CONSUMED (OUTBOUND)*');
    if (outboundStock.isNotEmpty) {
      for (final s in outboundStock) {
        final prod = s.displayProductName;
        final qty = '${s.quantity} ${s.displayMetricUnitName}';
        final purpose = s.cleanRemarks != null && s.cleanRemarks!.isNotEmpty ? ' — ${s.cleanRemarks}' : '';
        buffer.writeln('  🔻 $prod: -$qty$purpose');
      }
    } else {
      buffer.writeln('  _No material consumption logged today_');
    }

    buffer.writeln('\n━━━━━━━━━━━━━━━━━━━━');
    final pendingCount = dayCash.where((c) => c.status != TransactionStatus.approved).length +
        dayStock.where((s) => s.status != TransactionStatus.approved).length;
    buffer.writeln('⏳ *Pending Verifications:* $pendingCount items');
    buffer.writeln('📲 _Generated by SKCPL Construction App_');

    return buffer.toString();
  }

  /// Launches WhatsApp with pre-filled message, or copies text to clipboard as fallback.
  static Future<bool> shareToWhatsApp(String messageText) async {
    // 1. Copy to clipboard immediately so the user never loses the message
    await Clipboard.setData(ClipboardData(text: messageText));

    // 2. Try launching WhatsApp web or app scheme
    final encoded = Uri.encodeComponent(messageText);
    final waUri = Uri.parse('https://wa.me/?text=$encoded');
    final nativeUri = Uri.parse('whatsapp://send?text=$encoded');

    try {
      if (await canLaunchUrl(nativeUri)) {
        await launchUrl(nativeUri);
        return true;
      }
    } catch (_) {}

    try {
      if (await canLaunchUrl(waUri)) {
        await launchUrl(waUri, mode: LaunchMode.externalApplication);
        return true;
      }
    } catch (_) {}

    return false; // Indicating clipboard copy succeeded, but direct launch couldn't trigger
  }

  /// Triggers the professional PDF layout and print/download
  static Future<void> exportPdfReport({
    required String siteName,
    required DateTime date,
    required List<StockTransactionModel> stockTransactions,
    required List<CashTransactionModel> cashTransactions,
    String? siteLoginId,
  }) async {
    await PdfService.generateAndPrintDailySummary(
      siteName: siteName,
      date: date,
      stockTransactions: stockTransactions,
      cashTransactions: cashTransactions,
      siteLoginId: siteLoginId,
    );
  }
}
